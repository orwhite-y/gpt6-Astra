def skill_text(row: tuple[str, str, str, str, str, str, str]) -> str:
    leaf_id, parent, title, kws, s1, s2, s3 = row
    return (
        f"---\n"
        f"name: {leaf_id}\n"
        f"description: >\n"
        f"  CHA leaf workflow for {title}. Use when: {kws}.\n"
        f"parent: {parent}\n"
        f"---\n\n"
        f"# {title} · LEAF-{leaf_id}\n\n"
        f"父技能：`{parent}`\n"
        f"关键词：{kws}\n\n"
        f"第一步 {s1}\n\n"
        f"第二步 {s2}\n\n"
        f"第三步 {s3}\n\n"
        f"缺参用 TARGET / HOST / TOKEN / OFFSET / PATCH_BYTE / PAYLOAD / SERIAL / ROLE_A / ROLE_B。收口：当前:对象 / 结果 / 下一步\n"
    )


def index_md() -> str:
    lines = ["## 小类三拍总表 · CHA-LEAVES", "",
             "参考 GitHub 上「一类一面 SKILL.md」的拆法（Claude-Red / rev-skills / pentest-skills / DFIR skills），正文原创。",
             "工单先匹配小类，再执行该小类三拍；匹配不上再退回七条父技能。",
             "",
             "| 小类 | 技能 id | 父技能 | 关键词 |",
             "| --- | --- | --- | --- |"]
    for leaf_id, parent, title, kws, *_ in LEAVES:
        lines.append(f"| {title} | `{leaf_id}` | `{parent}` | {kws} |")
    lines.append("")
    return "\n".join(lines) + "\n"


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    for old in OUT.glob("*.md"):
        if old.name == "INDEX.md":
            continue
        old.unlink()
    for row in LEAVES:
        (OUT / f"{row[0]}.md").write_text(skill_text(row), encoding="utf-8", newline="\n")
    (OUT / "INDEX.md").write_text(index_md(), encoding="utf-8", newline="\n")
    print(f"emitted {len(LEAVES)} leaves -> {OUT}")


if __name__ == "__main__":
    main()
